"""Render the source register and the validity matrix as Markdown, generated from the JSON (never edited by hand), so
the human-readable documents cannot drift from the data. Read-only on the register and the database."""
from __future__ import annotations

import json
from pathlib import Path

from .register import REGISTER

HEAD = "**Business line:** HomepreunerHub / HerBiz (Agent championship) · **Generated by** `python3 -m compliance_agent.rag_c render` · **Not legal or tax advice.**"


def _c(x) -> str:
    return "" if x is None else str(x).replace("|", "\\|").replace("\n", " ")


def register_md(register_path: Path = REGISTER) -> str:
    r = json.loads(Path(register_path).read_text(encoding="utf-8"))
    L = [f"# HerBiz: Compliance Agent — Official source register (register v{r['register_version']}, as of {r['as_of']})", "", HEAD, "",
         "> This is the **source landscape we know of**, not a claim of complete legal coverage. Three tiers:",
         "> **A** captured in the knowledge base (all `candidate`, unverified extraction, none approved);",
         "> **B** researched candidates (`activated: false`, not ingested); **C** instruments recorded from the documents' own amendment lists.",
         "", "## Tier A — captured in the knowledge base", "",
         "| Source | Version | Title | Authority | Lang / status | URL | Retrieved | Latest amendment in file (effective) | FTA currency | KB status | Verified |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in r["sources"]:
        for v in s.get("versions", []):
            cur = (v.get("currency_observations") or [{}])[-1].get("currency", "")
            L.append(f"| {s['source_id']} | {v['version_id']} | {_c(s['title'])} | {_c(s['issuing_authority'])} | {s['language']} / {_c(s['translation_status'])} | "
                     f"{v['url']} | {v['retrieved_at']} | {_c(v.get('latest_effective_as_stated'))} | {_c(cur[:60])} | {v['kb_status']} | {v['verification_status']} |")
        if not s.get("versions"):
            obs = (s.get("currency_observations") or [{}])[-1].get("currency", "not collected")
            L.append(f"| {s['source_id']} | — | {_c(s['title'])} | {_c(s['issuing_authority'])} | {s['language']} / {_c(s['translation_status'])} | "
                     f"— | — | — | {_c(obs[:60])} | not collected | — |")
    L += ["", "## Tier B — researched candidates (not activated, not ingested)", "",
          "| Candidate | Title | Type / scope | Lang | Issue | Effective | URL | Evidence | Confidence | Status |", "|---|---|---|---|---|---|---|---|---|---|"]
    for c in r.get("candidates", []):
        L.append(f"| {c['candidate_id']} | {_c(c.get('title'))} | {_c(c.get('document_type'))} / {_c(c.get('scope'))} | {_c(c.get('language'))} | "
                 f"{_c(c.get('issue_date'))} | {_c(c.get('effective_date'))} | {_c(c.get('url'))} | {_c(c.get('evidence'))[:140]} | {c.get('confidence')} | {c['verification_status']} |")
    L += ["", "## Tier C — instruments (amendment relationships)", "",
          "| Instrument | Title | Amends | Issued | Effective | Articles affected | List complete? | Evidence |", "|---|---|---|---|---|---|---|---|"]
    for i in r.get("instruments", []):
        L.append(f"| {i['instrument_id']} | {_c(i['title'])} | {i['amends_source']} | {_c(i.get('issued'))} | {_c(i.get('effective'))} | "
                 f"{', '.join(i.get('articles_affected') or []) or 'not recorded'} | {'yes' if i.get('articles_list_complete') else 'no'} | {_c(i['evidence'])[:120]} |")
    eff = r.get("instrument_effects", [])
    if eff:
        L += ["", "Article additions and repeals: " + "; ".join(f"{e['instrument_id']} {e['effect']} {e['source_id']} Art. {e['article']}" for e in eff) + "."]
    L += ["", "## Gaps", "", "| Id | Gap | Owner | Status |", "|---|---|---|---|"] + \
         [f"| {g['id']} | {_c(g['what'])} | {_c(g.get('owner'))} | {_c(g.get('status', 'open'))} |" for g in r.get("gaps", [])]
    L += ["", "## Register history", ""] + [f"- **{c['version']}** ({c['date']}): {c['what']}" for c in r["changes"]]
    return "\n".join(L) + "\n"


def validity_md(validity: dict, amap: dict, claims: dict) -> str:
    m = validity["_meta"]
    L = [f"# HerBiz: Compliance Agent — Source validity matrix (as of {m['generated_for_date']}, register v{m['register_version']})", "", HEAD, "",
         f"Database: {m['database_passages']} passages (md5 `{m['database_md5'][:12]}…`). **Approved versions: "
         f"{', '.join(validity['approved_versions']) or 'none'}.** Rule: {m['rule']}", "",
         "## 1. Versions", "", "| Version | KB status | Verified | Selected as current | Outdated (missing in-force amendments) | FTA currency | Superseded by |",
         "|---|---|---|---|---|---|---|"]
    av = {v["version_id"]: v for v in amap["versions"]}
    for v in validity["versions"]:
        miss = ", ".join(av[v["version_id"]]["missing_in_force_instruments"]) or "none"
        L.append(f"| {v['version_id']} | {v['kb_status']} | {v['verification_status']} | {'yes' if v['selected_as_current'] else 'no'} | "
                 f"{'yes: ' + miss if v['outdated'] else 'no'} | {v['fta_currency']} | {_c(v['superseded_by'])} |")
    L += ["", "## 2. Provision issues (what retrieval may not certify)", "", "| Issue | Kind | Provisions | Message |", "|---|---|---|---|"]
    L += [f"| {i['id']} | {i['kind']} | {_c(', '.join(i['provisions']))} | {_c(i['message'])} |" for i in validity["issues"]]
    L += ["", "## 3. Value claims and conflicts", "", "| Claim | Topic | Value | Source | Locator | Integrity |", "|---|---|---|---|---|---|"]
    L += [f"| {c['claim_id']} | {c['topic']} | {c['value']} {c['unit']} | {c['source_id']} | {_c(c.get('locator'))} | {c['integrity']} |" for c in claims["claims"]]
    L += ["", "Conflicts: " + ("; ".join(f"**{c['topic']}**: " + " vs ".join(f"{v[0]} {v[1]}" for v in c["values"]) for c in claims["conflicts"]) or "none") + "."]
    L += ["", "## 4. Status vocabulary", "",
          "- **candidate**: captured, not reviewed (every version today). **verified**: a named person checked the extraction against the original. "
          "**approved**: a qualified UAE tax reviewer approved the version (D3; nobody named yet). Only *approved* + no issue = certifiable.",
          "- Evidence levels: observed, observed_listing_only, observed_in_file, snippet_only, supplied, unresolved."]
    return "\n".join(L) + "\n"
