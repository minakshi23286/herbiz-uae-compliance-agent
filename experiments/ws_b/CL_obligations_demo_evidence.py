"""HerBiz 360 obligations engine: demonstration evidence for Workstream A (synthetic profiles only, offline, no spend).

Writes docs/360/demo/CL_obligations_demo_<policy>.json and CL_OBLIGATIONS_DEMO_EVIDENCE.md.
Usage: python3 experiments/ws_b/CL_obligations_demo_evidence.py [--as-of 2026-10-17] [--out docs/360/demo]
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from compliance_agent.obligations import engine as E, validity as V  # noqa: E402

DB_COPY = ROOT / "data" / "CL_ws_b_exact_copy.sqlite3"
FIXTURE = ROOT / "fixtures" / "obligations" / "CL_synthetic_profiles_360.json"
SHORT = {"applicable": "Applies (TEST)", "not_applicable": "Does not apply", "potentially_applicable": "May apply (draft)",
         "insufficient_information": "Need information", "blocked_pending_legal_validation": "Blocked: legal validation"}


def build(as_of: dt.date, out: Path) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    sv = V.load_pinned(DB_COPY, today=as_of.isoformat())
    profiles = json.loads(FIXTURE.read_text(encoding="utf-8"))["profiles"]
    # owner demo: fail-closed policy only (D-062); the reviewer preview is never part of the owner demo
    reports = {pol: [E.assess(p, sv, as_of, pol) for p in profiles] for pol in E.OWNER_POLICIES}
    for pol, reps in reports.items():
        (out / f"CL_obligations_demo_{pol}.json").write_text(json.dumps(reps, indent=1, ensure_ascii=False), encoding="utf-8")
    violations = [v for reps in reports.values() for r in reps for v in E.wording_violations(r)]
    md = [f"# HerBiz 360 obligations engine — demonstration evidence (synthetic)", "",
          f"Business line: HomepreunerHub / HerBiz · Workstream B · as of {as_of} · status: built, verified offline (synthetic only)", "",
          f"> {E.BANNER}", "",
          f"Source validity: {'available' if sv.available else 'UNAVAILABLE (fails closed)'} — WS-C contract v1.1 pinned at `{V.PINNED_COMMIT}`"
          f"{'' if sv.available else ': ' + str(sv.error)}. Approved official sources today: 0.", "",
          f"Wording violations: {len(violations)}.", "",
          "Policy: fail closed (founder decision D-062). Unreviewed legal rules give no decisions, dates, eligibility or filing instructions.", "",
          "## Summary by profile", "",
          "| Profile | Persona | " + " | ".join(SHORT[s] for s in E.STATES) + " | Owner questions |", "|" + "---|" * (len(E.STATES) + 3)]
    for rb, p in zip(reports["blocked"], profiles):
        cells = [str(rb["summary"][s]) for s in E.STATES]
        nq = len(rb["profile_gaps"]["questions"]) + sum(len(o["missing_information"]) for o in rb["obligations"])
        md.append(f"| {p['profile_id']} | {p['persona']} | " + " | ".join(cells) + f" | {nq} |")
    for rb, p in zip(reports["blocked"], profiles):
        md += ["", f"## {p['profile_id']} — {p['persona']}", ""]
        if rb["profile_gaps"]["questions"]:
            md.append("Profile questions: " + "; ".join(rb["profile_gaps"]["questions"].values()))
            md.append("")
        md += ["| Obligation | State | Why / missing | Deadline | Documents ready |", "|---|---|---|---|---|"]
        for o in rb["obligations"]:
            why = "; ".join(o["why"][:2]) or o["reason"]
            if o["missing_information"]:
                why += " — ask: " + "; ".join(m["question"] for m in o["missing_information"][:2])
            dl = o["deadline"]["due_date"] or ("text only" if o["deadline"]["kind"] == "draft_text" else "—")
            docs = o["documents"]
            rd = "—" if docs["readiness"] is None else f"{len(docs['ready'])}/{len(docs['required'])}"
            md.append(f"| {o['id']} {o['title']} | {SHORT[o['state']]} | {why.replace('|', '/')} | {dl} | {rd} |")
    md += ["", "Generated by `experiments/ws_b/CL_obligations_demo_evidence.py`. Synthetic data; TEST RULES are not law; "
           "corporate tax items are blocked placeholders by founder decision D-061."]
    (out / "CL_OBLIGATIONS_DEMO_EVIDENCE.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return {"validity_available": sv.available, "violations": len(violations), "profiles": len(profiles)}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--as-of", default="2026-10-17")
    ap.add_argument("--out", default=str(ROOT / "docs" / "360" / "demo"))
    a = ap.parse_args()
    print(build(dt.date.fromisoformat(a.as_of), Path(a.out)))
